#!/usr/bin/env python3
"""Generate ugv_limits_test.world: twelve parallel lanes, each with ONE obstacle the Jackal-class UGV must climb (experiment X-A1).

Lane i is at y = 3*(i - 5.5). Ramps (lanes 0-5): 10, 15, 20, 25, 30, 35 deg, 4 m of slope starting at x = 3, then a 3 m plateau.
Steps (lanes 6-11): STEPS_CM (cm) boxes, 3 m deep, starting at x = 3.
Usage: python3 make_limits_world.py > ugv_limits_test.world
"""
import math

RAMPS_DEG = [10, 15, 20, 25, 30, 35]
STEPS_CM = [8, 9, 10, 11, 12, 14]          # run 1 used 4, 8, 12, 16, 20, 24 (4/8 crossed, 12+ blocked); run 2 narrows it down


def box(name, pose, size):
    s = " ".join(map(str, size))
    return (f'<model name="{name}"><static>true</static><pose>{pose}</pose><link name="l">'
            f'<collision name="c"><geometry><box><size>{s}</size></box></geometry></collision>'
            f'<visual name="v"><geometry><box><size>{s}</size></box></geometry></visual></link></model>')


def lanes():
    out = []
    for i, d in enumerate(RAMPS_DEG):
        th, L = math.radians(d), 4.0
        y = 3.0 * (i - 5.5)
        out.append(box(f"ramp_{d}", f"{3 + L / 2 * math.cos(th):.4f} {y} {L / 2 * math.sin(th):.4f} 0 {-th:.5f} 0", (L, 2.0, 0.05)))
        top, x_top = L * math.sin(th), 3 + L * math.cos(th)         # a plateau at the top: driving off a 0.7 m edge flips ANY robot
        out.append(box(f"top_{d}", f"{x_top + 1.4:.4f} {y} {top / 2 - 0.025:.4f} 0 0 0", (3.0, 2.0, top + 0.05)))
    for j, h in enumerate(STEPS_CM):
        y = 3.0 * (6 + j - 5.5)
        out.append(box(f"step_{h}cm", f"4.5 {y} {h / 200:.4f} 0 0 0", (3.0, 2.0, h / 100)))
    return "\n    ".join(out)


